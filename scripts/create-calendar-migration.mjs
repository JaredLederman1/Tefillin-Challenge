import {HebrewCalendar, flags} from '@hebcal/core';
import {writeFileSync,readFileSync} from 'node:fs';
// Store authoritative civil-date exemptions, including both Diaspora Yom Tov days.
const days=[];
for(let year=2020;year<=2040;year++)for(const event of HebrewCalendar.calendar({year,il:false})){
 if(event.getFlags()&flags.CHAG){const d=event.greg();days.push(`${d.getFullYear()}-${String(d.getMonth()+1).padStart(2,'0')}-${String(d.getDate()).padStart(2,'0')}`);}
}
const prefix=`-- Generated by scripts/create-calendar-migration.mjs using @hebcal/core. Diaspora, 2020–2040.
-- Chol Hamoed is intentionally unchanged pending an explicit policy decision.
begin;
create table public.wrap_calendar_exemptions(day date primary key);
alter table public.wrap_calendar_exemptions enable row level security;
revoke all on public.wrap_calendar_exemptions from anon,authenticated;
insert into public.wrap_calendar_exemptions(day)
select unnest(string_to_array('${[...new Set(days)].sort().join(',')}',','))::date;
create function public.is_required_wrap_day(d date) returns boolean
language plpgsql stable security definer set search_path='' as $$
begin
 if d is null or d<date '2020-01-01' or d>date '2040-12-31' then raise exception 'Challenge calendar needs an update'; end if;
 return extract(dow from d)<>6 and not exists(select 1 from public.wrap_calendar_exemptions e where e.day=d);
end $$;
revoke all on function public.is_required_wrap_day(date) from public,anon;
grant execute on function public.is_required_wrap_day(date) to authenticated,service_role;
create function public.wrap_comment_words(value text) returns integer
language sql immutable set search_path='' as $$
 select count(*)::integer from regexp_matches(coalesce(value,''),U&'[^[:space:]\\00A0\\1680\\2000-\\200A\\2028\\2029\\202F\\205F\\3000\\FEFF]+','g');
$$;
revoke all on function public.wrap_comment_words(text) from public,anon;
grant execute on function public.wrap_comment_words(text) to authenticated,service_role;
-- Existing posts are preserved; the new caption rule applies to future submissions.
`;
